"""Size generated weather cards, validate the complete set, and make a preview.

Usage: python tools/prepare_weather_cards.py --sources path/to/sources.json
The source JSON is a list of {"code": "0", "path": "...png"} objects.
Only resizing/format conversion is performed; artwork is generated by imagegen.
"""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, ImageOps


ROOT = Path(__file__).resolve().parents[1]
CARDS = ROOT / "resources" / "weather"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sources", type=Path)
    parser.add_argument("--partial", action="store_true")
    args = parser.parse_args()
    manifest = json.loads((CARDS / "manifest.json").read_text(encoding="utf-8"))
    expected = {str(i) for i in range(48)} | {"na"}
    entries = {card["code"]: card for card in manifest["cards"]}
    assert set(entries) == expected and len(manifest["cards"]) == 49
    if args.sources:
        for source in json.loads(args.sources.read_text(encoding="utf-8")):
            code = source["code"]
            assert code in expected, code
            destination = CARDS / entries[code]["file"]
            if destination.exists():
                continue
            with Image.open(source["path"]) as original:
                # Preserve proportions; trim only the tiny aspect-ratio rounding
                # difference in generated dimensions before reducing to the card.
                card = ImageOps.fit(original.convert("RGB"), (320, 720),
                                    method=Image.Resampling.LANCZOS)
                card.save(destination, "JPEG", quality=95, subsampling=0,
                          optimize=True)
    existing = {p.stem for p in CARDS.glob("*.jpg")}
    assert existing <= expected, existing - expected
    if not args.partial:
        assert existing == expected, f"Missing cards: {expected - existing}"
    hashes = set()
    columns, thumb_w, thumb_h, label_h = 7, 160, 360, 42
    preview = Image.new("RGB", (columns * thumb_w, 7 * (thumb_h + label_h)),
                        "#15202c")
    draw = ImageDraw.Draw(preview)
    font = ImageFont.truetype("C:/Windows/Fonts/arial.ttf", 12)
    small = ImageFont.truetype("C:/Windows/Fonts/arial.ttf", 11)
    for index, entry in enumerate(manifest["cards"]):
        path = CARDS / entry["file"]
        x, y = (index % columns) * thumb_w, (index // columns) * (thumb_h + label_h)
        if path.exists():
            with Image.open(path) as card:
                assert card.size == (320, 720), path
                assert card.mode == "RGB", path
                digest = hashlib.sha256(card.tobytes()).hexdigest()
                assert digest not in hashes, f"Duplicate artwork: {path}"
                hashes.add(digest)
                preview.paste(card.resize((thumb_w, thumb_h), Image.Resampling.LANCZOS), (x, y))
        draw.text((x + 5, y + thumb_h + 3), entry["code"] + "  " + entry["condition"],
                  font=font if len(entry["condition"]) < 22 else small, fill="white")
    preview_path = ROOT / "tools" / "weather-cards-preview.jpg"
    preview.save(preview_path, quality=90, subsampling=0)
    total = sum(p.stat().st_size for p in CARDS.glob("*.jpg"))
    print(f"Validated {len(existing)}/49 distinct RGB cards at 320 x 720; {total:,} bytes")
    print(preview_path)


if __name__ == "__main__":
    main()
